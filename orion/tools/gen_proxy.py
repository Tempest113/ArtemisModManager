"""Generates the forwarding layer of the winmm.dll stub from the real System32 winmm.dll's export table (D14).

    python orion/tools/gen_proxy.py [output_dir]      (default: orion/build/generated)

Writes stub_exports.asm (one `jmp [stub_targets + i*8]` thunk per export, so any signature forwards unchanged),
stub_exports.h (names and ordinals, used to fill the table at load) and stub.def (the linker's export table, with
the original ordinals). Nothing here is checked in: build.bat runs it, and the files come from the machine's own winmm.dll.
"""

import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_exports(path):
    """[(name or None, ordinal)] for a PE file; stops on a forwarder export, which a plain jump can't represent."""
    d = open(path, "rb").read()
    u16 = lambda o: struct.unpack_from("<H", d, o)[0]
    u32 = lambda o: struct.unpack_from("<I", d, o)[0]
    pe = u32(0x3C)
    opt = pe + 24
    nsec, osz = u16(pe + 6), u16(pe + 20)
    doff = opt + (112 if u16(opt) == 0x20B else 96)
    secs = [struct.unpack_from("<IIII", d, opt + osz + 40 * i + 8) for i in range(nsec)]

    def r2o(rva):
        for vsize, va, rsize, rptr in secs:
            if va <= rva < va + max(vsize, rsize):
                return rva - va + rptr
        raise ValueError(hex(rva))

    cstr = lambda o: d[o:d.index(b"\0", o)].decode()
    exp_rva, exp_size = u32(doff), u32(doff + 4)
    e = r2o(exp_rva)
    base, nfun, nnames = u32(e + 16), u32(e + 20), u32(e + 24)
    fun, nam, ords = r2o(u32(e + 28)), r2o(u32(e + 32)), r2o(u32(e + 36))
    names = {u16(ords + 2 * i): cstr(r2o(u32(nam + 4 * i))) for i in range(nnames)}
    exports = []
    for i in range(nfun):
        rva = u32(fun + 4 * i)
        if not rva:
            continue
        if exp_rva <= rva < exp_rva + exp_size:
            raise SystemExit(f"export #{base + i} is a forwarder; this generator doesn't handle those")
        exports.append((names.get(i), base + i))
    return exports


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "generated")
    dll = "winmm.dll"
    exports = read_exports(os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", dll))
    note = f"; Generated by orion/tools/gen_proxy.py from System32\\{dll}. Do not edit.\n"

    asm = [note, "EXTERN stub_targets:QWORD", ".code"]
    deff = [note, "LIBRARY winmm", "EXPORTS"]
    for i, (name, ordinal) in enumerate(exports):
        asm += [f"Stub_{i} PROC", f"  jmp qword ptr [stub_targets + {i * 8}]", f"Stub_{i} ENDP"]
        deff.append(f"  {name}=Stub_{i} @{ordinal}" if name else f"  Stub_{i} @{ordinal} NONAME")
    asm.append("END")

    h = [note.replace(";", "//", 1), "#pragma once", "", "struct StubExport {",
         "  const char* name;  // null for ordinal-only exports", "  unsigned short ordinal;", "};", "",
         "constexpr StubExport kStubExports[] = {"]
    h += [f'    {{{chr(34) + n + chr(34) if n else "nullptr"}, {o}}},' for n, o in exports]
    h += ["};", "constexpr int kStubExportCount = sizeof(kStubExports) / sizeof(kStubExports[0]);", ""]

    os.makedirs(out, exist_ok=True)
    for rel, lines in (("stub_exports.asm", asm), ("stub.def", deff), ("stub_exports.h", h)):
        with open(os.path.join(out, rel), "w", newline="\r\n") as f:
            f.write("\n".join(lines) + "\n")
    print(f"{dll}: {len(exports)} exports ({sum(1 for n, _ in exports if not n)} ordinal-only)")


if __name__ == "__main__":
    main()
